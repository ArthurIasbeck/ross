def simulate_with_optimal_x0(A, B, t_ref, i_ref, y_ref):
    """Simulate a state-space model using the shared initial-state solver.

    This wrapper preserves the import path used by the results module while
    keeping the implementation in :mod:`system_identification`.

    Parameters
    ----------
    A : np.ndarray
        State matrix of the discrete state-space model.
    B : np.ndarray
        Input matrix of the discrete state-space model.
    t_ref : array_like
        Reference time vector.
    i_ref : array_like
        Reference input signal, representing magnetic-bearing current.
    y_ref : array_like
        Reference output signal, representing displacement.

    Returns
    -------
    x_pred : np.ndarray
        Predicted state trajectory.
    x0_opt : np.ndarray
        Initial state estimate obtained by least squares.
    """
    from ross.bearings.magnetic.system_identification import (
        simulate_with_optimal_x0 as _simulate_with_optimal_x0,
    )

    return _simulate_with_optimal_x0(A, B, t_ref, i_ref, y_ref)


class AmbSystemIdentification:
    """Coordinate transfer-function identification for magnetic bearings.

    This class groups the data-driven identification and Hankel model
    reduction workflows used to obtain one model for each orthogonal direction
    of every magnetic bearing in a rotor.

    Parameters
    ----------
    rotor : ross.Rotor
        Rotor model containing one or more
        :class:`ross.MagneticBearingElement` objects.
    """

    def __init__(self, rotor):
        """Initialize the magnetic-bearing identification coordinator.

        Parameters
        ----------
        rotor : ross.Rotor
            Rotor model whose magnetic bearings will be identified or reduced.
        """
        self.rotor = rotor

    def run_amb_system_identification(self, method, **kwargs):
        """Identify models for the rotor's magnetic-bearing directions.

        The ``"de"``, ``"slsqp"`` and ``"ss"`` methods generate disturbances,
        simulate the rotor time response, and identify a model from the
        resulting current and displacement signals.  ``"de"`` uses
        differential evolution, ``"slsqp"`` uses SLSQP optimization, and
        ``"ss"`` identifies a discrete state-space model through
        :class:`SystemIdentification`.  The ``"reduce"`` method builds a
        model directly from the rotor and reduces it using Hankel singular
        values instead of using simulated measurements.

        The returned result contains one model for each direction of every
        magnetic bearing.  Direction keys have the form
        ``"<bearing tag> (node <node>) - v"`` and
        ``"<bearing tag> (node <node>) - w"``.  For data-driven methods,
        corresponding fitness values, disturbance signals, and reference
        data are also stored.  For ``"reduce"``, the disturbance and
        reference-data entries are empty because no time-domain identification
        data are generated, while ``fits`` contains one frequency-response
        fitness for each input/output channel pair.

        Parameters
        ----------
        method : {"de", "slsqp", "ss", "reduce"}
            Identification method.  ``"de"``, ``"slsqp"`` and ``"ss"`` use
            data generated by time-response simulations.  ``"reduce"`` uses
            balanced Hankel model reduction.
        num_modes : int, optional
            Number of modes used in the modal reduction. For ``method="reduce"``,
            this is the number of modes retained in the reduced model. For the
            data-driven methods, it is the number of modes used by the time-response
            simulation. Default is 10.
        dt : float, optional
            Time step, in seconds, used to generate the disturbance and to
            simulate the rotor response.  Default is 1e-1.
        speed : float, optional
            Rotor speed, in rad/s, used by the time-response simulation and
            by the model-reduction workflow. Default is 0.
        time_to_converge : float or None, optional
            Time, in seconds, before which simulated samples are discarded.
            Use ``None`` to retain the complete response.  Default is 1.0.
        disturbance_changing_time : float, optional
            Duration, in seconds, of each transition in the generated
            disturbance. Default is 0.5.
        disturbance_steady_time : float, optional
            Nominal duration, in seconds, of each steady portion of the
            generated disturbance. Default is 5.
        disturbance_n_steps : int, optional
            Number of randomly stepped values used to generate the
            disturbance. Default is 60.
        disturbance_step_amplitude : float, optional
            Amplitude scale of the generated disturbance steps. Default is
            ``10e-6``.
        disturbance_chirp_amplitude : float, optional
            Amplitude of the logarithmic chirp generated for frequency-response
            analysis. Default is ``10e-6``.
        disturbance_chirp_min_frequency : float, optional
            Initial frequency, in Hz, of the logarithmic chirp. Default is
            ``1.0``.
        disturbance_chirp_max_frequency : float, optional
            Final frequency, in Hz, of the logarithmic chirp. Default is
            ``1000``.
        p : int or array_like of int, optional
            State-space prediction window length. A scalar value is used for
            every magnetic-bearing direction. If an array-like value is
            provided, it must contain exactly ``2 * n_ambs`` values, where
            ``n_ambs`` is the number of magnetic bearings. Each element is
            used for one direction in bearing order (``v``, then ``w``), and
            may itself be an array-like collection of candidate window
            lengths to test for that direction. Used only for
            ``method="ss"``. Default is 20.

        Returns
        -------
        results : ross.AmbSystemIdentificationResult
            Result object containing ``models``, ``time_data``,
            ``frequency_data``, ``fit``, and the selected ``method``. The
            domain data contain the simulated signals and measured/model
            responses. For
            data-driven methods, ``fit`` contains ``time`` and ``freq`` maps
            with one fitness value in percent for each identified model.
            ``fits`` contains the frequency-response fitness values for
            ``method="reduce"``. The result also provides plotting methods
            for model responses, disturbances, and reference data.
            ``time_data`` and ``frequency_data`` are empty for
            ``method="reduce"``.

        Examples
        --------
        >>> from ross.bearings.magnetic.amb_models import rotor_example_amb_simple
        >>> from ross.bearings.magnetic.amb_system_identification import (
        ...     AmbSystemIdentification,
        ... )
        >>> rotor = rotor_example_amb_simple()
        >>> identification = AmbSystemIdentification(rotor)
        >>> results = identification.run_amb_system_identification(
        ...     "ss", dt=1e-3, speed=600.0, time_to_converge=1.0
        ... )
        >>> results.method
        'ss'
        >>> len(results.models) == 2 * len(
        ...     [b for b in rotor.bearing_elements
        ...      if b.__class__.__name__ == "MagneticBearingElement"]
        ... )
        True

        A reduced model can be generated by selecting the reduction method:

        >>> results = identification.run_amb_system_identification(
        ...     "reduce", num_modes=10, speed=600.0
        ... )
        >>> results.method
        'reduce'
        """

        from ross import AmbSystemIdentificationResult

        valid_methods = {"de", "slsqp", "ss", "reduce"}
        if method not in valid_methods:
            raise ValueError(
                f"Unknown method '{method}'. Use 'de', 'slsqp', 'ss' or 'reduce'."
            )

        models = {}
        fits = {}
        fit = {"time": {}, "freq": {}}
        time_data = {}
        frequency_data = {}
        channel_names = None

        if method in ["de", "slsqp", "ss"]:
            data_driven_kwargs = {
                **kwargs,
                "method": method,
                "models": models,
                "time_data": time_data,
                "fit": fit,
                "frequency_data": frequency_data,
            }
            self._run_amb_tf_data_driven_identification(**data_driven_kwargs)

        elif method == "reduce":
            reduction_kwargs = {
                **kwargs,
                "models": models,
                "fits": fits,
            }
            self._run_amb_tf_reduction_identification(**reduction_kwargs)

            ambs = get_ambs(self.rotor)
            channel_names = [
                f"{amb.tag} - {axis}"
                for amb in ambs
                for axis in ("Current v", "Current w")
            ]

        return AmbSystemIdentificationResult(
            models=models,
            fits=fits,
            fit=fit if method in {"de", "slsqp", "ss"} else None,
            method=method,
            channel_names=channel_names,
            time_data=time_data,
            frequency_data=frequency_data,
        )

    def _run_amb_tf_reduction_identification(self, **kwargs):
        """Build and reduce one model for each magnetic-bearing direction.

        For every magnetic bearing in ``self.rotor``, this method creates a
        :class:`ReduceModel`, plots its Hankel singular values, and reduces the
        two orthogonal SISO models to the requested number of modes.  The resulting
        transfer functions are stored in ``models`` under ``- v`` and ``- w``
        keys.  Since this method performs model reduction rather than a
        time-domain experiment, it inserts empty disturbance arrays and empty
        reference-data arrays for each model.  The fitness of each input/output
        frequency response is calculated and stored in ``fits`` using the
        response labels shown by the result's frequency-response plot.

        This is an internal helper called by
        :meth:`run_amb_system_identification` when ``method="reduce"``.  The
        dictionaries passed as arguments are modified in place; the method has
        no explicit return value.

        Parameters
        ----------
        num_modes : int, optional
            Number of modes retained in each reduced transfer-function model.
            Default is 10.
        speed : float, optional
            Rotor speed, in rad/s, used to build the original and reduced
            models. Default is 0.
        models : dict
            Dictionary to receive the reduced models. It is updated in place
            with the ``G_v`` and ``G_w`` models for every magnetic bearing.
        fits : dict
            Dictionary to receive one fitness value, in percent, for each
            input/output frequency response. It is updated in place using the
            frequency-response labels.

        Returns
        -------
        None
            The input dictionaries contain the generated models and metadata
            after the method completes.

        Examples
        --------
        >>> from ross.bearings.magnetic.amb_models import rotor_example_amb_simple
        >>> from ross.bearings.magnetic.amb_system_identification import (
        ...     AmbSystemIdentification,
        ... )
        >>> rotor = rotor_example_amb_simple()
        >>> identification = AmbSystemIdentification(rotor)
        >>> models = {}
        >>> identification._run_amb_tf_reduction_identification(
        ...     num_modes=10,
        ...     speed=600.0,
        ...     models=models,
        ... )
        >>> len(models) == 2
        True
        """
        num_modes = kwargs.get("num_modes", 10)
        speed = kwargs.get("speed", 0)
        omega_min = kwargs.get("omega_min", 0.01)
        omega_max = kwargs.get("omega_max", 10_000)
        num_freqs = kwargs.get("num_freqs", 1_000)

        models = kwargs["models"]
        fits = kwargs["fits"]

        original_model_builder = ReduceModel(
            rotor=deepcopy(self.rotor), speed=speed, num_modes=-1
        )
        reduced_model_builder = ReduceModel(
            rotor=deepcopy(self.rotor), speed=speed, num_modes=num_modes
        )

        original_model = original_model_builder.build_model()
        reduced_model = reduced_model_builder.build_model()

        omega = np.logspace(np.log10(omega_min), np.log10(omega_max), num_freqs)
        original_mag, original_phase, _ = ct.frequency_response(original_model, omega)
        reduced_mag, reduced_phase, _ = ct.frequency_response(reduced_model, omega)

        freq_resp_original = original_mag * np.exp(1j * original_phase)
        freq_resp_reduced = reduced_mag * np.exp(1j * reduced_phase)

        # TODO: É muito estranho eu repetir essa lógica aqui. Não faz sentido. Depois vou precisar pensar em uma forma melhor de fazer isso
        from ross import AmbSystemIdentificationResult

        ambs = get_ambs(self.rotor)
        channel_names = [
            f"{amb.tag} - {axis}" for amb in ambs for axis in ("Current v", "Current w")
        ]
        label_result = AmbSystemIdentificationResult(
            models={}, fits={}, method="reduce", channel_names=channel_names
        )
        num_rows, num_columns = freq_resp_original.shape[:2]
        labels = label_result._get_frequency_response_labels(num_rows, num_columns)

        for row in range(num_rows):
            for column in range(num_columns):
                original_response = freq_resp_original[row, column, :]
                reduced_response = freq_resp_reduced[row, column, :]
                fits[labels[row * num_columns + column]] = 100 * (
                    1
                    - np.linalg.norm(original_response - reduced_response)
                    / np.linalg.norm(original_response - np.mean(original_response))
                )

        models["reduced_model"] = reduced_model
        models["original_model"] = original_model

    def _run_amb_tf_data_driven_identification(self, method, **kwargs):
        """Identify magnetic-bearing models from simulated time-response data.

        The method generates a smooth, randomly stepped disturbance and applies
        it to each input direction of each magnetic bearing, one direction at
        a time.  For every experiment it runs :meth:`run_time_response`,
        extracts the magnetic-bearing current and displacement signals, and
        optionally removes the initial transient.  An
        :class:`SystemIdentification` instance then identifies the model and
        calculates its fitness using ``method``.

        Two entries are created for each magnetic bearing: one for the ``v``
        direction and one for the ``w`` direction.  The input dictionaries are
        modified in place.  The fitness values are percentages indexed by the
        same direction keys as the identified models.

        Parameters
        ----------
        method : {"de", "slsqp", "ss"}
            Data-driven identification algorithm passed to
            :meth:`SystemIdentification.identify`.
        dt : float, optional
            Time step, in seconds, used for the generated disturbance and
            time-response simulation. Default is 1e-1.
        speed : float, optional
            Rotor speed, in rad/s, used by :meth:`run_time_response`.
            Default is 0.
        time_to_converge : float or None, optional
            Time, in seconds, before which samples are discarded.  If
            ``None``, all generated samples are used. Default is 1.0.
        num_modes : int, optional
            Number of modes used by the time-response simulation.
            Default is 10.
        models : dict
            Dictionary to populate with the identified models.  It is updated
            in place.
        fit : dict
            Dictionary with ``time`` and ``freq`` sub-dictionaries, each
            populated with the corresponding fitness by identified direction.
        time_data : dict
            Dictionary to populate with identification time signals, indexed
            by identified direction.
        frequency_data : dict
            Dictionary to populate with chirp signals and measured/model
            frequency responses, indexed by identified direction.
        disturbance_changing_time : float, optional
            Duration, in seconds, of each transition in the generated
            disturbance. Default is 0.5.
        disturbance_steady_time : float, optional
            Nominal duration, in seconds, of each steady portion of the
            generated disturbance. Default is 5.
        disturbance_n_steps : int, optional
            Number of randomly stepped values used to generate the
            disturbance. Default is 60.
        disturbance_step_amplitude : float, optional
            Amplitude scale of the generated disturbance steps. Default is
            ``10e-6``.
        p : int or array_like of int, optional
            State-space prediction window length. A scalar value is used for
            every magnetic-bearing direction. If an array-like value is
            provided, it must contain exactly ``2 * n_ambs`` values, where
            ``n_ambs`` is the number of magnetic bearings. Each element is
            used for one direction in bearing order (``v``, then ``w``), and
            may itself be an array-like collection of candidate window
            lengths to test for that direction. Used only when
            ``method="ss"``. Default is 20.

        Returns
        -------
        None
            The input dictionaries contain the identified models, fitness
            values, disturbances, and reference data after the method
            completes.

        Examples
        --------
        >>> from ross.bearings.magnetic.amb_models import rotor_example_amb_simple
        >>> from ross.bearings.magnetic.amb_system_identification import (
        ...     AmbSystemIdentification,
        ... )
        >>> rotor = rotor_example_amb_simple()
        >>> identification = AmbSystemIdentification(rotor)
        >>> models, time_data, frequency_data = {}, {}, {}
        >>> fit = {"time": {}, "freq": {}}
        >>> identification._run_amb_tf_data_driven_identification(
        ...     "ss",
        ...     dt=1e-3,
        ...     speed=600.0,
        ...     time_to_converge=1.0,
        ...     num_modes=10,
        ...     models=models,
        ...     time_data=time_data,
        ...     fit=fit,
        ...     frequency_data=frequency_data,
        ...     disturbance_changing_time=0.5,
        ...     disturbance_steady_time=5,
        ...     disturbance_n_steps=60,
        ...     disturbance_step_amplitude=10e-6,
        ... )
        >>> len(models) == len(fit["time"]) == len(fit["freq"])
        >>> len(models) == len(time_data) == len(frequency_data)
        True
        """
        dt = kwargs.get("dt", 1e-3)
        speed = kwargs.get("speed", 0)
        time_to_converge = kwargs.get("time_to_converge", 1.0)
        num_modes = kwargs.get("num_modes", 10)
        disturbance_changing_time = kwargs.get("disturbance_changing_time", 0.5)
        disturbance_steady_time = kwargs.get("disturbance_steady_time", 5)
        disturbance_n_steps = kwargs.get("disturbance_n_steps", 60)
        disturbance_step_amplitude = kwargs.get("disturbance_step_amplitude", 10e-6)
        disturbance_chirp_amplitude = kwargs.get("disturbance_chirp_amplitude", 10e-6)
        disturbance_chirp_min_frequency = kwargs.get(
            "disturbance_chirp_min_frequency", 1.0
        )
        disturbance_chirp_max_frequency = kwargs.get(
            "disturbance_chirp_max_frequency", 1000
        )
        p = kwargs.get("p", 20)
        models = kwargs["models"]
        time_data = kwargs["time_data"]
        fit = kwargs["fit"]
        frequency_data = kwargs["frequency_data"]

        ambs = get_ambs(self.rotor)
        n_ambs = len(ambs)
        n_axes = 2 * n_ambs

        # Validate the p values.
        p_values = self._process_prediction_window(p, n_axes)

        for i in range(n_axes):
            # Compute the disturbance used to determine the time response for identification.
            t_ident, d_ident = get_ident_disturbance(
                dt,
                changing_time=disturbance_changing_time,
                steady_time=disturbance_steady_time,
                n_steps=disturbance_n_steps,
                step_amplitude=disturbance_step_amplitude,
            )
            t_fr = t_ident.copy()

            # Determine the time response for identification.
            d_array_ident = np.zeros((len(t_ident), 2 * n_ambs))
            d_array_ident[:, i] = d_ident
            F = np.zeros((t_ident.size, self.rotor.ndof))

            response_ident = self.rotor.run_time_response(
                speed,
                F,
                t_ident,
                disturbance=d_array_ident,
                weight=False,
                num_modes=num_modes,
            )

            current_ident = response_ident.I[:, i]
            disp_ident = response_ident.v_amb[:, i]

            # Trim the data.
            if time_to_converge is not None:
                current_ident = current_ident[t_ident >= time_to_converge]
                disp_ident = disp_ident[t_ident >= time_to_converge]
                d_ident = d_ident[t_ident >= time_to_converge]
                t_ident = t_ident[t_ident >= time_to_converge]

            # Identify the model.
            amb_system_identification = SystemIdentification(
                i_ref=current_ident, y_ref=disp_ident, t_ref=t_ident
            )
            model, fit_time, model_output_ident = amb_system_identification.identify(
                method=method, p=p_values[i]
            )

            # Compute the disturbance used to determine the time response for the frequency response.
            d_fr = disturbance_chirp_amplitude * chirp(
                t_fr,
                f0=disturbance_chirp_min_frequency,
                f1=disturbance_chirp_max_frequency,
                t1=float(t_fr[-1]),
                method="logarithmic",
                phi=-90,
            )
            d_array_fr = np.zeros((len(t_fr), n_axes))
            d_array_fr[:, i] = d_fr

            response_fr = self.rotor.run_time_response(
                speed,
                F,
                t_fr,
                disturbance=d_array_fr,
                weight=False,
                num_modes=num_modes,
            )

            current_fr = response_fr.I[:, i]
            disp_fr = response_fr.v_amb[:, i]

            # Trim the data.
            if time_to_converge is not None:
                current_fr = current_fr[t_fr >= time_to_converge]
                disp_fr = disp_fr[t_fr >= time_to_converge]
                d_fr = d_fr[t_fr >= time_to_converge]
                t_fr = t_fr[t_fr >= time_to_converge]

            f, abs_fr, phase_fr, fr, _ = compute_freq_resp(t_fr, disp_fr, current_fr)

            model_magnitude, model_phase, _ = ct.frequency_response(
                model, 2 * np.pi * f
            )
            model_fr = np.squeeze(model_magnitude * np.exp(1j * model_phase))
            fit_freq = self._frequency_response_fitness(fr, model_fr)

            # Store the computed data.
            mma = ambs[i // 2]
            key = f"{mma.tag} - v" if i % 2 else f"{mma.tag} - w"
            models[key] = model
            fit["time"][key] = fit_time
            fit["freq"][key] = fit_freq
            time_data[key] = {
                "t_ident": t_ident,
                "d_ident": d_ident,
                "current_ident": current_ident,
                "disp_ident": disp_ident,
                "model_output_ident": model_output_ident,
            }
            frequency_data[key] = {
                "t_fr": t_fr,
                "d_fr": d_fr,
                "current_fr": current_fr,
                "disp_fr": disp_fr,
                "f": f,
                "abs_fr": abs_fr,
                "phase_fr": phase_fr,
                "fr": fr,
                "model_magnitude": np.squeeze(model_magnitude),
                "model_phase": np.squeeze(model_phase),
            }

    @staticmethod
    def _frequency_response_fitness(reference, prediction):
        """Calculate frequency-domain fitness for complex FRF values."""
        reference = np.asarray(reference)
        prediction = np.asarray(prediction)
        reference_norm = np.linalg.norm(reference - np.mean(reference))
        if reference_norm == 0:
            return 0.0
        return float(
            100 * (1 - np.linalg.norm(reference - prediction) / reference_norm)
        )

    @staticmethod
    def _process_prediction_window(p, n_axes):
        """Return one prediction window value for each magnetic-bearing axis.

        Parameters
        ----------
        p : int or array_like of int
            Scalar window length to apply to every axis, or a sequence with
            one window length (or candidate collection) per axis.
        n_axes : int
            Number of magnetic-bearing directions.

        Returns
        -------
        p_values : list
            Prediction window values in magnetic-bearing direction order.

        Raises
        ------
        ValueError
            If ``p`` is neither a scalar nor a sequence with ``n_axes``
            entries.
        """
        if np.isscalar(p):
            return [p] * n_axes

        try:
            p_values = list(p)
        except TypeError as exc:
            raise ValueError(
                "'p' must be a scalar or a sequence with one value for "
                f"each magnetic-bearing direction ({n_axes} values)."
            ) from exc

        if len(p_values) != n_axes:
            raise ValueError(
                "When 'p' is a sequence, it must contain exactly "
                f"{n_axes} values, one for each magnetic-bearing direction."
            )

        return p_values
